package com.mo.ugreenforcoloros

/**
 * T6 命令常量表。
 *
 * ================== 数据来源（重要） ==================
 *
 * 全部来自 [RUNTIME_VERIFIED] 真机取证：
 * 用 LSPosed 模块 Hook 官方"声学"APP（com.ugreen.iot）的
 * BluetoothSocket 读写流，逐字节捕获其发出的原始命令。
 *
 * 采集时间：2026-10-03 16:29 ~ 16:31
 * 设备：OnePlus 15 / PLK110 / Android 17
 * 耳机：UGREEN HiTune T6  90:A0:BE:2D:5E:CA
 *
 * ================== 命令帧结构 ==================
 *
 *     偏移  含义
 *     0-2   固定头  AA BB CC
 *     3     功能域  09 = 降噪/通透   08 = 游戏模式
 *                   04 = 状态查询    01 = 心跳
 *     4     固定 01
 *     5-6   参数（2 字节）
 *     7     随命令固定不变的字节（算法未知，见下）
 *
 * ================== 关于第 7 字节 ==================
 *
 * 它由命令内容唯一确定（同一参数多次发送完全相同，
 * 跨连接、跨会话都不变），但【不是】任何常见算法：
 *
 *     已用脚本穷举并排除：
 *       · 前缀求和（所有长度）        ✗
 *       · 前缀异或（所有长度）        ✗
 *       · sum ^ xor 组合变体          ✗
 *       · CRC-8 全家族（256 多项式 ×
 *         初值 × 输入/输出反射 × xorout） ✗
 *
 * 尚未反编译 APK 确认。因此本表采取【抄现成值】策略：
 * 直接使用捕获到的原始 8 字节，不自己计算校验。
 *
 * ================== 应答格式 ==================
 *
 *     DD EE FF | 功能域 | 01 | 01 | 参数 | 尾部2字节
 *
 * 应答会把命令的参数【原样回显】在第 6 字节，
 * 因此可以用应答确认耳机当前状态。
 *
 * ================== 参数 -> 官方 APP 显示名（已实测确认） ==================
 *
 * 由用户逐条点击我们的按钮、同时观察官方"声学"APP 的显示，
 * 并与 bt_stack 日志的时间戳双向核对得出：
 *
 *     参数 A1  ->  官方显示"降噪深度"     （最深）
 *     参数 B1  ->  官方显示"降噪中度"
 *     参数 C1  ->  官方显示"降噪轻度"
 *     参数 A0  ->  官方显示"降噪关"
 *     参数 C0  ->  官方显示"降噪关"（与 A0 显示相同，区别未知）
 *     参数 C2  ->  官方显示"环境音"（即通透）
 *
 * 可见 09 族的参数是"深度阶梯"：
 *     高位字母 A -> B -> C 表示档位递降，
 *     末位 1 = 深度档位，0 = 关，2 = 环境音。
 *
 * ================== 已确认的官方实现事实（来自反编译） ==================
 *
 * 官方 APP 在设备表里把 T6 定义为【非 BLE 设备】：
 *
 *     "UGREEN HiTune T6" -> { ISBLE = FALSE,
 *                             SERVICE_ID = "66666666-6666-6666-6666-666666666666",
 *                             CHARACTERISTIC_SEND = "77777777-..." }
 *
 * 对照：HiTune Max6 才是 ISBLE = TRUE。
 * 这与取证日志"官方 APP 只走 RFCOMM/SPP、从不使用 BLE GATT"完全一致。
 *
 * => 因此【SPP 才是 T6 的官方命令通道】，
 *    本表同时支持 BLE 写入仅用于实测验证该结论。
 */
object UgreenT6Commands {

    // ---------------------------------------------------------------
    // 系统（ColorOS）模式 → T6 命令
    // ---------------------------------------------------------------

    /**
     * 把 ColorOS 的降噪模式值翻译成 T6 命令。
     *
     * ★ 这组模式值是【从 SystemUI 的资源表反查确认的】：
     *
     *     5  = 降噪      (qs_noise_reduction_open        = "Noise cancellation")
     *     2  = 通透      (qs_noise_reduction_transparent = "Transparency")
     *     1  = 关闭
     *     10 = 自适应    (T6 不支持)
     *
     * 产品决定："降噪"对应 T6 的【深度降噪】档。
     *
     * 抽成共用函数的原因：主界面（手动测试）和后台服务（系统请求）
     * 都要做同样的映射，放在这里避免两处各写一份而走偏。
     *
     * @return Pair(命令字节, 中文标签)；无法识别的模式返回 null
     */
    fun forSystemMode(mode: Int): Pair<ByteArray, String>? =
        when (mode) {
            5 -> ANC_DEEP to "降噪 深度"
            2 -> ANC_AMBIENT to "环境音"
            1 -> ANC_OFF to "降噪 关"
            else -> null
        }

    // ---------------------------------------------------------------
    // 降噪 / 通透（功能域 09）
    // ---------------------------------------------------------------

    /**
     * 降噪 关（标准）。
     *
     * 官方 APP 显示"降噪关"。这是官方 APP 自己最常用的关闭值。
     */
    val ANC_OFF = hex("AA BB CC 09 01 A0 A0 2A")

    /** 降噪 深度（最深档）。官方 APP 显示"降噪深度"。 */
    val ANC_DEEP = hex("AA BB CC 09 01 A1 61 EA")

    /** 环境音 / 通透。官方 APP 显示"环境音"。 */
    val ANC_AMBIENT = hex("AA BB CC 09 01 C2 21 C3")

    /** 降噪 中度。官方 APP 显示"降噪中度"。 */
    val ANC_MEDIUM = hex("AA BB CC 09 01 B1 60 26")

    /**
     * 降噪 关（另一种取值）。
     *
     * 官方 APP 在这个参数下【也显示"降噪关"】。
     * 与 A0 的区别目前未知，因此单独保留、单独命名，
     * 不做合并，避免丢信息。
     */
    val ANC_OFF_ALT = hex("AA BB CC 09 01 C0 A0 02")

    /** 降噪 轻度。官方 APP 显示"降噪轻度"。 */
    val ANC_LIGHT = hex("AA BB CC 09 01 C1 61 C2")

    // ---------------------------------------------------------------
    // 游戏模式（功能域 08）
    // ---------------------------------------------------------------

    /** 游戏模式 开。 */
    val GAME_MODE_ON = hex("AA BB CC 08 01 01 30 52")

    /** 游戏模式 关。 */
    val GAME_MODE_OFF = hex("AA BB CC 08 01 00 F1 92")

    // ---------------------------------------------------------------
    // 连接维护
    // ---------------------------------------------------------------

    /**
     * 状态查询。
     *
     * 官方 APP 在每次连上后立刻发它，
     * 会收到 27 字节的状态包作为应答。
     */
    val QUERY_STATUS = hex("AA BB CC 04 01 00 31 91")

    /**
     * 心跳。
     *
     * 官方 APP 连上后连发两条，无应答。
     */
    val HEARTBEAT = hex("AA BB CC 01 01 00 21 90")

    // ---------------------------------------------------------------

    /** 把带空格的 HEX 转成 ByteArray。 */
    private fun hex(text: String): ByteArray =
        UgreenT6Hex.fromHex(text) ?: ByteArray(0)

    /**
     * 给界面用的命令清单。
     *
     * 标签用的是【官方 APP 实测显示的名称】，
     * 由用户逐条测试并与 BT 日志时间戳双向核对确认，
     * 不再使用推测的档位名。
     */
    fun menu(): List<Triple<String, String, ByteArray>> = listOf(
        Triple("降噪 关", "09 01 A0", ANC_OFF),
        Triple("降噪 深度", "09 01 A1", ANC_DEEP),
        Triple("降噪 中度", "09 01 B1", ANC_MEDIUM),
        Triple("降噪 轻度", "09 01 C1", ANC_LIGHT),
        Triple("环境音", "09 01 C2", ANC_AMBIENT),
        Triple("[对照] 也显示降噪关", "09 01 C0", ANC_OFF_ALT),
        Triple("游戏模式 开", "08 01 01", GAME_MODE_ON),
        Triple("游戏模式 关", "08 01 00", GAME_MODE_OFF),
        Triple("状态查询", "04 01 00", QUERY_STATUS),
        Triple("心跳", "01 01 00", HEARTBEAT)
    )
}
